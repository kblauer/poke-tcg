def render_tilemap(tiles_png, tilemap_bin, pals, pal_base, w_tiles, h_tiles, out):
    """A GBA 4bpp background: its 32-wide tilemap's entries (tile, flips, palette) over tiles.png, `pals` loaded from slot `pal_base`."""
    tim = Image.open(os.path.join(SRC, tiles_png))
    tw, tidx = tim.size[0] // 8, tim.load()
    data = open(os.path.join(SRC, tilemap_bin), 'rb').read()
    img = Image.new('RGBA', (w_tiles * 8, h_tiles * 8))
    px = img.load()
    for ty in range(h_tiles):
        for tx in range(w_tiles):
            i = ty * 32 + tx
            e = data[i * 2] | data[i * 2 + 1] << 8
            tile, hf, vf, pal = e & 0x3ff, e >> 10 & 1, e >> 11 & 1, e >> 12
            sx, sy = tile % tw * 8, tile // tw * 8
            if sy >= tim.size[1]:
                continue
            for y in range(8):
                for x in range(8):
                    v = tidx[sx + (7 - x if hf else x), sy + (7 - y if vf else y)] & 15
                    c = (pal - pal_base) * 16 + v
                    px[tx * 8 + x, ty * 8 + y] = (*(pals[c] if 0 <= c < len(pals) else (0, 0, 0)), 255)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    img.save(out, optimize=True)


