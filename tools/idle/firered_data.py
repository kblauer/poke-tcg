def save_indexed(src_png, out, pal=None, crop=None):
    """An indexed PNG as RGBA, with `pal` (a JASC palette) for its colours if given, colour 0 see-through."""
    im = Image.open(os.path.join(SRC, src_png))
    if pal:
        flat = [c for col in read_pal(pal) for c in col]
        im.putpalette(flat + [0] * (768 - len(flat)))
    if crop:
        im = im.crop(crop)
    rgba = im.convert('RGBA')
    px, idx = rgba.load(), im.load()
    for y in range(im.size[1]):
        for x in range(im.size[0]):
            if idx[x, y] == 0:
                px[x, y] = (0, 0, 0, 0)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    rgba.save(out, optimize=True)


