HEADER = "// Generated by tools/idle/firered_data.py from the pret/pokefirered decompilation ({}). Don't edit by hand.\n"


def read(path):
    return open(os.path.join(SRC, path), encoding='utf8').read()


def key(const, prefix):
    """MOVE_KARATE_CHOP -> 'karate-chop'."""
    return const[len(prefix):].lower().replace('_', '-')


def js(v):
    """A value as TypeScript source, single-quoted."""
    if isinstance(v, str):
        return "'" + v.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n') + "'"
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return '[' + ', '.join(js(x) for x in v) + ']'
    if isinstance(v, dict):
        return '{ ' + ', '.join((k if re.match(r'^[A-Za-z_]\w*$', k) else js(k)) + ': ' + js(x) for k, x in v.items()) + ' }' if v else '{}'
    raise TypeError(v)


def write(name, source, body):
    open(os.path.join(OUT_TS, name), 'w', encoding='utf8', newline='\n').write(HEADER.format(source) + body)


# Display names: the game's capitals in title case, with the joined spellings written as the later games do.
WORD_FIXES = {
    'Doubleslap': 'DoubleSlap', 'Thunderpunch': 'ThunderPunch', 'Thundershock': 'ThunderShock', 'Solarbeam': 'SolarBeam',
    'Smokescreen': 'SmokeScreen', 'Dynamicpunch': 'DynamicPunch', 'Dragonbreath': 'DragonBreath', 'Extremespeed': 'ExtremeSpeed',
    'Ancientpower': 'AncientPower', 'Bubblebeam': 'BubbleBeam', 'Sonicboom': 'SonicBoom', 'Poisonpowder': 'PoisonPowder',
    'Vicegrip': 'ViceGrip', 'Pokemon': 'Pokémon', 'Pp': 'PP', 'Hp': 'HP', 'Tm': 'TM', 'Hm': 'HM', 'Ss': 'S.S.', 'Pokedoll': 'Poké Doll',
    'Grasswhistle': 'GrassWhistle', 'Featherdance': 'FeatherDance', 'Dragondance': 'DragonDance',
}


def title(s):
    s = s.replace('POKé', 'POKE').replace('é', 'e').replace('{PKMN}', 'POKEMON')
    out = []
    for w in s.split(' '):
        w = '-'.join(p[:1].upper() + p[1:].lower() for p in w.split('-'))
        out.append(WORD_FIXES.get(w, w))
    return ' '.join(out).replace('Poke Ball', 'Poké Ball').replace('Poke Doll', 'Poké Doll').replace('Poke ', 'Poké ')


def names(path, prefix):
    return {m.group(1): m.group(2) for m in re.finditer(r'\[(' + prefix + r'\w+)\]\s*=\s*_\("([^"]*)"\)', read(path))}


def struct_blocks(text, prefix):
    """[PREFIX_X] = { .a = 1, ... } blocks, as {const: {field: raw value}}."""
    out = {}
    # A block ends at its closing line, never running into the next entry (`[X] = {0},` has none).
    for m in re.finditer(r'\[(' + prefix + r'\w+)\]\s*=\s*\{((?:(?!\n\s*\[)[\s\S])*?)\n\s*\},', text):
        out[m.group(1)] = {f.group(1): f.group(2).strip() for f in re.finditer(r'\.(\w+)\s*=\s*(\{[^}]*\}|[^,\n]+)', m.group(2))}
    return out


def num(v):
    v = v.strip()
    m = re.match(r'PERCENT_FEMALE\(([\d.]+)\)', v)
    if m:
        return min(254, int(float(m.group(1)) * 255 / 100))
    return {'MON_GENDERLESS': 255, 'MON_MALE': 0, 'MON_FEMALE': 254, 'TRUE': 1, 'FALSE': 0}.get(v, None) if not re.match(r'^-?(0x)?[\da-fA-F]+$', v) else int(v, 0)


def blocks(text):
    """The top-level { ... } blocks of a list's body."""
    depth, cur, out = 0, '', []
    for ch in text:
        if ch == '{':
            depth += 1
            if depth == 1:
                cur = ''
                continue
        if ch == '}':
            depth -= 1
            if depth == 0:
                out.append(cur)
                continue
        if depth >= 1:
            cur += ch
    return out


