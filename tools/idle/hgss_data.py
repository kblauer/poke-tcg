def trainer_key(c):
    """TRAINER_YOUNGSTER_JOEY -> 'youngster-joey'; a name the constant repeats once (TRAINER_LEADER_FALKNER_FALKNER,
    TRAINER_ELITE_FOUR_WILL_WILL_2) once only: 'leader-falkner', 'elite-four-will-2'."""
    words = [w for w in key(c, 'TRAINER_').split('-') if w]
    tail = [words.pop()] if words[-1].isdigit() else []
    for n in range(len(words) // 2, 0, -1):
        if words[-n:] == words[-2 * n:-n]:
            words = words[:-n]
            break
    return '-'.join(words + tail)


