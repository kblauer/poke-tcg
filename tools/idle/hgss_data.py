def read(path):
    return open(os.path.join(SRC, path), encoding='utf8').read()


def load(path):
    return json.loads(read(path))


def key(const, prefix):
    """MOVE_KARATE_CHOP -> 'karate-chop'."""
    return const[len(prefix):].lower().replace('_', '-')


def js(v):
    """A value as TypeScript source, single-quoted."""
    if isinstance(v, str):
        return "'" + v.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n') + "'"
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return '[' + ', '.join(js(x) for x in v) + ']'
    if isinstance(v, dict):
        return '{ ' + ', '.join((k if re.match(r'^[A-Za-z_]\w*$', k) else js(k)) + ': ' + js(x) for k, x in v.items()) + ' }' if v else '{}'
    raise TypeError(v)


def write(name, source, body):
    open(os.path.join(OUT_TS, name), 'w', encoding='utf8', newline='\n').write(HEADER.format(source) + body)


def narc(path):
    """The files in a Nintendo NARC archive, in order."""
    d = open(os.path.join(SRC, path), 'rb').read()
    o = struct.unpack_from('<H', d, 12)[0]
    assert d[o:o + 4] == b'BTAF', path
    size, n = struct.unpack_from('<IH', d, o + 4)
    fat = [struct.unpack_from('<II', d, o + 12 + 8 * i) for i in range(n)]
    o += size
    assert d[o:o + 4] == b'BTNF', path
    o += struct.unpack_from('<I', d, o + 4)[0]
    assert d[o:o + 4] == b'GMIF', path
    return [d[o + 8 + s:o + 8 + e] for s, e in fat]


def messages(n):
    """A text archive (files/msgdata/msg/msg_<n>.json) in English, its lines joined (a line break kept as \\n)."""
    out = []
    for m in load(f'files/msgdata/msg/msg_{n:04d}.json')['messages']:
        t = m.get('en_US', '')
        out.append(''.join(t) if isinstance(t, list) else t)
    return out


def constants(path, prefix, start=None, end=None):
    """A header's numbered constants ({value: name}, the first name a value has), between `start` and `end` if given."""
    text = read(path)
    if start:
        text = text[text.index(start):]
    if end:
        text = text[:text.index(end)]
    out = {}
    for c, n in re.findall(r'#define (' + prefix + r'\w+)\s+(\d+)\b', text):
        out.setdefault(int(n), c)
    return out


def flat(text):
    """A message as one line (the Pokédex's and the moves' descriptions: their line breaks as spaces)."""
    return re.sub(r'\s+', ' ', text.replace('\\n', ' ').replace('\n', ' ')).strip()


# Kanto's keys for the same things (FireRed's constants), by name: an HGSS item or move named as a Kanto one keeps its key.
def kanto_keys(path):
    return {re.sub(r'[^a-z0-9]', '', name.lower().replace("\\'", "'")): k
            for k, name in re.findall(r"^  '([^']+)': \{ name: '((?:[^'\\]|\\.)*)'", open(os.path.join(GEN1, path), encoding='utf8').read(), re.M)}


def same_key(table, name, fallback):
    return table.get(re.sub(r'[^a-z0-9]', '', name.lower()), fallback)


