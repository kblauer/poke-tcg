def learnset(n):
    out = []
    for i in range(0, len(wotbl[n]) - 1, 2):
        v = struct.unpack_from('<H', wotbl[n], i)[0]
        if v == 0xFFFF:
            break
        out.append([v >> 9, move_key[move_consts[v & 0x1FF]]])
    return out


def evolutions(c):
    out = []
    for e in evo.get(c, []):
        if e['method'] == 'EVO_NONE':
            continue
        # A stone is Kanto's 'item' (EVO_ITEM: stoneEvolution); every other method EVO_'s, lower case.
        method = 'item' if e['method'] == 'EVO_STONE' else e['method'][len('EVO_'):].lower()
        x = {'method': method, 'into': species_id[e['target']]}
        p = e['param']
        if e['method'] in LEVELLED or e['method'] == 'EVO_BEAUTY':
            x['level' if e['method'] != 'EVO_BEAUTY' else 'beauty'] = int(p)
        elif e['method'] in HELD:
            x['item'] = item(p if isinstance(p, str) else item_consts[int(p)])
        elif e['method'] == 'EVO_HAS_MOVE':
            x['move'] = move_key[p if isinstance(p, str) else move_consts[int(p)]]
        elif e['method'] == 'EVO_OTHER_PARTY_MON':
            x['with'] = species_id[p] if isinstance(p, str) else int(p)
        out.append(x)
    return out


