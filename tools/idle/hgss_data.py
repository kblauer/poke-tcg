# ---- Wild encounters ----
TIMES = {'morn': 'morning', 'day': 'day', 'nite': 'night'}


def version(v, game):
    """A value HeartGold and SoulSilver may differ in (a dict of the two), for one game."""
    return v[game] if isinstance(v, dict) and game in v else v


def slots(mons, game, time=None):
    out = []
    for m in mons:
        lvl = version(m['level'], game)
        lo, hi = (version(lvl['min'], game), version(lvl['max'], game)) if isinstance(lvl, dict) else (lvl, lvl)
        sp = m['species']
        if isinstance(sp, dict) and time:
            sp = sp[time]
        sp = version(sp, game)
        out.append([lo, hi, species_id.get(sp, 0)])
    return out


def table(e, game):
    """A map's tables in one game: land by time of day, the rest as they are."""
    out = {}
    if e['land']['rate']:
        out['land'] = {'rate': e['land']['rate'], **{t: slots(e['land']['mons'], game, k) for k, t in TIMES.items()}}
    for src, dst in (('surf', 'water'), ('rock_smash', 'rockSmash')):
        if e[src]['rate']:
            out[dst] = {'rate': e[src]['rate'], 'mons': slots(e[src]['mons'], game)}
    for src, dst in (('old_rod', 'oldRod'), ('good_rod', 'goodRod'), ('super_rod', 'superRod')):
        if e['fishing'][src]['rate']:
            out[dst] = {'rate': e['fishing'][src]['rate'], 'mons': slots(e['fishing'][src]['mons'], game)}
    return out


def merged(hg, ss):
    """HeartGold's table, its morning and night slots where they differ from the day's, and SoulSilver's Pokémon where its slots differ."""
    out = {}
    for name, t in hg.items():
        o = ss[name]
        if name == 'land':
            entry = {'rate': t['rate'], 'mons': t['day']}
            for time in ('morning', 'night'):
                if t[time] != t['day']:
                    entry[time] = t[time]
            alt = {}
            for time in ('morning', 'day', 'night'):
                diff = [[i, *s] for i, (s, h) in enumerate(zip(o[time], t[time])) if s != h]
                if diff:
                    alt[time] = diff
            if alt:
                entry['soulSilver'] = alt
        else:
            entry = {'rate': t['rate'], 'mons': t['mons']}
            diff = [[i, *s] for i, (s, h) in enumerate(zip(o['mons'], t['mons'])) if s != h]
            if diff:
                entry['soulSilver'] = {'day': diff}
        out[name] = entry
    return out


