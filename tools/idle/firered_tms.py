"""Makes the Idle Adventure's TMs and HMs (README: Idle Adventure, Buy TMs) from a checkout of the pret/pokefirered
decompilation: packages/idle/src/data/gen1/tms.ts, each machine's move (include/constants/items.h's aliases,
ITEM_TM01_FOCUS_PUNCH: 'tm01' teaches 'focus-punch') and the machines each species can learn
(src/data/pokemon/tmhm_learnsets.h), by Pokédex number, for the species the idle data has (data/gen1/species.ts).
Every move must be in data/gen1/moves.ts (tools/idle/firered_data.py).

Usage: python tools/idle/firered_tms.py <pokefirered checkout>."""
import os
import re
import sys

SRC = os.path.abspath(sys.argv[1])
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
DATA = os.path.join(ROOT, 'packages', 'idle', 'src', 'data', 'gen1')


def read(path):
    return open(os.path.join(SRC, path), encoding='utf8').read()


def key(const):
    """FOCUS_PUNCH -> 'focus-punch' (firered_data.py's keys)."""
    return const.lower().replace('_', '-')


def main():
    moves = set(re.findall(r"^  '([a-z0-9-]+)': \{", open(os.path.join(DATA, 'moves.ts'), encoding='utf8').read(), re.M))
    species = {k: int(i) for i, k in re.findall(r"\{ id: (\d+), key: '([a-z0-9-]+)'", open(os.path.join(DATA, 'species.ts'), encoding='utf8').read())}
    machines = re.findall(r'#define ITEM_((?:TM|HM)\d\d)_(\w+) ITEM_\1\b', read('include/constants/items.h'))
    if len(machines) != 58:
        sys.exit(f'Expected 50 TMs and 8 HMs, found {len(machines)}')
    teaches = {}
    for item, move in machines:
        if key(move) not in moves:
            sys.exit(f'{item} teaches {move}, not in moves.ts')
        teaches[item.lower()] = key(move)
    learners = {}
    text = read('src/data/pokemon/tmhm_learnsets.h')
    for const, body in re.findall(r'\[SPECIES_(\w+)\]\s*=\s*TMHM_LEARNSET\(([^;]*?)\),\n', text):
        if key(const) in species:
            learners[species[key(const)]] = [m.lower() for m in re.findall(r'TMHM\(((?:TM|HM)\d\d)_\w+\)', body)]
    missing = [k for k in species if species[k] not in learners]
    if missing:
        sys.exit(f'No learnset for {missing}')
    out = [
        "// Generated by tools/idle/firered_tms.py from the pret/pokefirered decompilation. Don't edit by hand.",
        '',
        "/** Each TM's and HM's move (items.h: ITEM_TM01_FOCUS_PUNCH), TM01 to TM50, then HM01 to HM08. */",
        'export const TM_MOVES: Record<string, string> = {',
        *[f"  {item}: '{move}'," for item, move in teaches.items()],
        '};',
        '',
        '/** The TMs and HMs each species can learn (tmhm_learnsets.h), by Pokédex number. */',
        'export const TM_LEARNERS: Record<number, string[]> = {',
        *[f"  {n}: [{', '.join(repr(m) for m in learners[n])}]," for n in sorted(learners)],
        '};',
    ]
    open(os.path.join(DATA, 'tms.ts'), 'w', encoding='utf8', newline='\n').write('\n'.join(out) + '\n')
    print(len(teaches), 'machines,', len(learners), 'species')


main()
