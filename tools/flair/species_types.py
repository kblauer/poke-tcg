"""Writes packages/campaign/src/species-types.ts: each Pokémon's types as Generation 3 had them (#1-386, before the
Fairy type), for card flair's effects (which effects a card is offered, by its National Pokédex number).

From PokeAPI's data (https://github.com/PokeAPI/pokeapi, data/v2/csv): pokemon_types.csv (today's types),
pokemon_types_past.csv (types a Pokémon had up to a generation) and types.csv (type names). A Pokémon takes its
earliest past entry from Generation 3 on, if it has one (Clefairy was Normal until Generation 6), otherwise today's.

  python tools/flair/species_types.py <folder with the three CSVs>
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

LAST = 386
GENERATION = 3


def rows(folder: Path, name: str):
    with open(folder / name, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def main() -> None:
    folder = Path(sys.argv[1])
    names = {r['id']: r['identifier'] for r in rows(folder, 'types.csv')}
    today: dict[int, list[tuple[int, str]]] = defaultdict(list)
    for r in rows(folder, 'pokemon_types.csv'):
        if int(r['pokemon_id']) <= LAST:
            today[int(r['pokemon_id'])].append((int(r['slot']), names[r['type_id']]))
    past: dict[tuple[int, int], list[tuple[int, str]]] = defaultdict(list)
    for r in rows(folder, 'pokemon_types_past.csv'):
        if int(r['pokemon_id']) <= LAST and int(r['generation_id']) >= GENERATION:
            past[(int(r['pokemon_id']), int(r['generation_id']))].append((int(r['slot']), names[r['type_id']]))
    types = []
    for dex in range(1, LAST + 1):
        earliest = min((g for (p, g) in past if p == dex), default=None)
        entry = past[(dex, earliest)] if earliest is not None else today[dex]
        assert entry, f'no types for #{dex}'
        types.append('/'.join(t for _, t in sorted(entry)))
    out = Path(__file__).resolve().parents[2] / 'packages/campaign/src/species-types.ts'
    lines = [
        '// Generated by tools/flair/species_types.py from PokeAPI\'s data: never edit by hand.',
        '',
        '/** Each Pokémon\'s types as Generation 3 had them, by National Pokédex number (index 0 is #1, up to #386), "/"-separated. */',
        'export const SPECIES_TYPES: readonly string[] = [',
        *[f"  '{t}', // #{i + 1}" for i, t in enumerate(types)],
        '];',
        '',
    ]
    out.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'wrote {out} ({len(types)} species)')


if __name__ == '__main__':
    main()
