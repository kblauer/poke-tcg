"""Writes packages/campaign/src/species-types.ts: each Pokémon's types as the era of its cards had them, for card flair's
effects (which effects a card is offered, by its National Pokédex number): #1-386 as Generation 3 had them, #387-649 (the
Generation 4 and 5 Pokémon) as Generation 5 had them. Never the Fairy type (added in Generation 6).

From PokeAPI's data (https://github.com/PokeAPI/pokeapi, data/v2/csv): pokemon_types.csv (today's types),
pokemon_types_past.csv (types a Pokémon had up to a generation) and types.csv (type names). A Pokémon takes its
earliest past entry from its era's generation on, if it has one (Clefairy was Normal until Generation 6, Togekiss
Normal/Flying), otherwise today's. The CSVs are PokeAPI's public data files, downloaded once (the raw files of its
GitHub repository, no account needed) into a folder of their own:

  python -I tools/flair/species_types.py <folder with the three CSVs>
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

LAST = 649
ERAS = [(386, 3), (649, 5)]  # up to this Pokédex number, the types as of this generation


def generation(dex: int) -> int:
    return next(g for last, g in ERAS if dex <= last)


def rows(folder: Path, name: str):
    with open(folder / name, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def main() -> None:
    folder = Path(sys.argv[1])
    names = {r['id']: r['identifier'] for r in rows(folder, 'types.csv')}
    today: dict[int, list[tuple[int, str]]] = defaultdict(list)
    for r in rows(folder, 'pokemon_types.csv'):
        if int(r['pokemon_id']) <= LAST:
            today[int(r['pokemon_id'])].append((int(r['slot']), names[r['type_id']]))
    past: dict[tuple[int, int], list[tuple[int, str]]] = defaultdict(list)
    for r in rows(folder, 'pokemon_types_past.csv'):
        if int(r['pokemon_id']) <= LAST and int(r['generation_id']) >= generation(int(r['pokemon_id'])):
            past[(int(r['pokemon_id']), int(r['generation_id']))].append((int(r['slot']), names[r['type_id']]))
    types = []
    for dex in range(1, LAST + 1):
        earliest = min((g for (p, g) in past if p == dex), default=None)
        entry = past[(dex, earliest)] if earliest is not None else today[dex]
        assert entry, f'no types for #{dex}'
        assert not any(t == 'fairy' for _, t in entry), f'#{dex} is Fairy'
        types.append('/'.join(t for _, t in sorted(entry)))
    out = Path(__file__).resolve().parents[2] / 'packages/campaign/src/species-types.ts'
    lines = [
        '// Generated by tools/flair/species_types.py from PokeAPI\'s data: never edit by hand.',
        '',
        '/** Each Pokémon\'s types as its cards\' era had them (#1-386 as Generation 3 had them, #387-649 as Generation 5 had them, never Fairy), by National Pokédex number (index 0 is #1, up to #649), "/"-separated. */',
        'export const SPECIES_TYPES: readonly string[] = [',
        *[f"  '{t}', // #{i + 1}" for i, t in enumerate(types)],
        '];',
        '',
    ]
    out.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'wrote {out} ({len(types)} species)')


if __name__ == '__main__':
    main()