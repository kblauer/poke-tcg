"""Who's That Pokémon?: a holo's Pokémon as a silhouette on the anime's screen (README: Who's That Pokémon?).

A holo mask (apps/web/public/holo-masks, made by tools/holo-masks) is opaque everywhere on the card but the Pokémon, so
the Pokémon's shape is the mask's transparent part inside the art window. It is painted the anime's dark blue with a
darker shadow below and right, and scaled into the burst on the left of template.png (the blank screen, 1920×1080).
Masks with no cut-out (the close-ups make_masks.py leaves foil all over) are skipped.

One screen (prints the card's id and name):
    python tools/whos-that/whos_that.py [--card ID] [--seed N] [--out FILE]
For the game (--export), which draws each silhouette itself while it's played (no pictures made ahead of time, the
user's: the API sends a round's shape, apps/api/src/whos-that.ts, and the browser paints it, utils/whosThat.ts, as here):
    python tools/whos-that/whos_that.py --export
writes apps/web/public/whos-that/template.webp (the screen at 1280×720) and the campaign's whos-that-cards.ts (the holos
whose mask has a cut-out, the cards the game picks from). Run with a Python that has Pillow and numpy, from the repo root.
"""
import argparse
import json
import random
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
MASKS = ROOT / 'apps/web/public/holo-masks'
SNAPSHOT = ROOT / 'packages/db/prisma/data/tcgdex-wotc.json'
TEMPLATE = Path(__file__).resolve().parent / 'template.png'
PUBLIC = ROOT / 'apps/web/public/whos-that'
CAMPAIGN_DATA = ROOT / 'packages/campaign/src/whos-that-cards.ts'

# The art windows of TCGdex's 600×825 scans, as make_masks.py's ART.
ART = {'wotc': (63, 97, 541, 428), 'ecard': (57, 103, 580, 400), 'ex': (46, 79, 554, 390)}
FILL = (36, 104, 164)
SHADOW = (20, 66, 112)
# The burst's box, as shares of the screen: left, top, width, height (the web app's utils/whosThat.ts places the
# silhouette there too, with the same colours, shadow and smoothing). The exported screen's width.
BOX = (0.09, 0.15, 0.40, 0.70)
EXPORT_WIDTH = 1280


def era(card_id):
    return 'ecard' if card_id.startswith('ecard') else 'ex' if card_id.startswith('ex') else 'wotc'


def shape(path):
    """The Pokémon (the mask's transparent part) in the art window, as an L image, or None if there's no cut-out."""
    alpha = Image.open(path).convert('RGBA').getchannel('A').crop(ART[era(path.stem)])
    pokemon = 255 - np.asarray(alpha, dtype=np.uint8)
    if not 0.05 < (pokemon > 128).mean() < 0.75:
        return None
    return Image.fromarray(pokemon)


def silhouette(sil, W, H):
    """The silhouette with its shadow, the size of the burst's box on a W×H screen (transparent around it)."""
    sil = sil.crop(sil.point(lambda v: 255 if v > 128 else 0).getbbox())
    sil = sil.filter(ImageFilter.GaussianBlur(0.8)).point(lambda v: 255 if v > 128 else 0)
    box_w, box_h = round(W * BOX[2]), round(H * BOX[3])
    off = round(H * 0.012)
    scale = min((box_w - off) / sil.width, (box_h - off) / sil.height)
    size = (round(sil.width * scale), round(sil.height * scale))
    sil = sil.resize(size, Image.LANCZOS).filter(ImageFilter.GaussianBlur(H / 1080))
    x, y = (box_w - off - size[0]) // 2, (box_h - off - size[1]) // 2
    out = Image.new('RGBA', (box_w, box_h), (0, 0, 0, 0))
    out.paste(Image.new('RGBA', size, SHADOW + (255,)), (x + off, y + off), sil)
    out.paste(Image.new('RGBA', size, FILL + (255,)), (x, y), sil)
    return out


def screen(sil, template):
    W, H = template.size
    out = template.convert('RGBA')
    out.alpha_composite(silhouette(sil, W, H), (round(W * BOX[0]), round(H * BOX[1])))
    return out.convert('RGB')


def card_names():
    return {c['id']: c['name'] for c in json.load(open(SNAPSHOT, encoding='utf8'))['cards']}


def export():
    names = card_names()
    PUBLIC.mkdir(parents=True, exist_ok=True)
    template = Image.open(TEMPLATE).convert('RGB')
    small = template.resize((EXPORT_WIDTH, round(template.height * EXPORT_WIDTH / template.width)), Image.LANCZOS)
    small.save(PUBLIC / 'template.webp', quality=82)
    ids = sorted(p.stem for p in MASKS.glob('*.png') if p.stem in names and shape(p) is not None)
    CAMPAIGN_DATA.write_text(
        "// Generated by tools/whos-that/whos_that.py --export: the holos whose mask has a cut-out, the cards Who's That Pokémon? picks from.\n"
        f'export const WHOS_THAT_CARDS: readonly string[] = {json.dumps(ids)};\n',
        encoding='utf8', newline='\n')
    print(f'{len(ids)} cards')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--card', help='a holo card id (default: one at random)')
    parser.add_argument('--seed', type=int, help='seed for the random pick')
    parser.add_argument('--out', default='whos-that-pokemon.png')
    parser.add_argument('--export', action='store_true', help="write every silhouette and the answers for the game")
    args = parser.parse_args()
    if args.export:
        return export()

    paths = [MASKS / f'{args.card}.png'] if args.card else sorted(MASKS.glob('*.png'))
    random.Random(args.seed).shuffle(paths)
    path, sil = next(((p, s) for p in paths if (s := shape(p)) is not None), (None, None))
    if sil is None:
        raise SystemExit(f'No cut-out in {args.card}\'s mask' if args.card else 'No mask with a cut-out')
    print(path.stem, card_names().get(path.stem, '?'))
    screen(sil, Image.open(TEMPLATE)).save(args.out)
    print('saved', args.out)


if __name__ == '__main__':
    main()
