// Writes src/effects/ex-template-data.ts: every attack of the EX sets after Ruby & Sapphire (ex2–ex16) whose TCGdex text
// matches one of the shared wordings (src/effects/ex-templates.ts). Run after changing the templates or the snapshot:
//   npx tsx scripts/generate-ex-templates.ts
import { readFileSync, writeFileSync } from 'node:fs';
import '../src/index.js';
import { matchTemplate, type TemplateUse } from '../src/effects/ex-templates.js';

interface Row {
  id: string;
  name: string;
  category: string;
  attacks?: { name: string; cost: string[] | null; damage: string | number | null; effect: string | null }[] | null;
}

const SETS = [...Array.from({ length: 15 }, (_, i) => `ex${i + 2}`), 'dp1', 'dpp', 'dp2', 'dp3', 'dp4', 'dp5', 'dp6', 'dp7', 'pl1', 'pl2', 'pl3', 'pl4', 'hgss1', 'hgssp', 'hgss2', 'hgss3', 'hgss4', 'col1', 'bw1', 'bw2', 'bw3', 'bw4', 'bw5', 'bw6', 'dv1', 'bw7', 'bw8', 'bw9', 'bw10', 'bw11'];
const rows: Row[] = JSON.parse(readFileSync(new URL('../../db/prisma/data/tcgdex-wotc.json', import.meta.url), 'utf8')).cards;
/** A string in single quotes, as the code has them. */
const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const order = (id: string) => [SETS.indexOf(id.split('-')[0]!), Number.parseInt(id.split('-')[1]!, 10) || 0];

const lines: string[] = [];
const misfits: string[] = [];
let matched = 0;
let unmatched = 0;
for (const r of rows.filter((c) => c.category === 'Pokemon' && SETS.includes(c.id.split('-')[0]!)).sort((a, b) => order(a.id)[0]! - order(b.id)[0]! || order(a.id)[1]! - order(b.id)[1]!)) {
  const uses: [string, TemplateUse][] = [];
  // Each attack name once, as the API has them.
  for (const a of (r.attacks ?? []).filter((x, i, all) => all.findIndex((y) => y.name === x.name) === i)) {
    if (!a.effect) continue;
    const m = matchTemplate(a.effect, r.name, Number.parseInt(String(a.damage ?? ''), 10) || 0, a.cost ?? []);
    if (!m) unmatched++;
    else if ('misfit' in m) misfits.push(`${r.id} ${r.name} – ${a.name} (${a.damage ?? ''}): ${m.misfit}`);
    else {
      matched++;
      uses.push([a.name, m]);
    }
  }
  if (uses.length) lines.push(`  ${q(r.id)}: { ${uses.map(([name, use]) => `${/^[A-Za-z]+$/.test(name) ? name : q(name)}: [${use.map((a) => (typeof a === 'number' ? a : q(a))).join(', ')}]`).join(', ')} }, // ${r.name}`);
}

writeFileSync(
  new URL('../src/effects/ex-template-data.ts', import.meta.url),
  [
    '// Generated by scripts/generate-ex-templates.ts from the TCGdex snapshot: the EX (ex2–ex16) and Gen 4 attacks whose wording is one of the',
    "// shared ones in ex-templates.ts, as [template, printed damage, ...the wording's numbers and words]. Don't edit by hand.",
    "import type { TemplateUse } from './ex-templates.js';",
    '',
    'export const EX_TEMPLATE_DATA: Record<string, Record<string, TemplateUse>> = {',
    ...lines,
    '};',
    '',
  ].join('\n'),
);
console.log(`${matched} attacks matched, ${unmatched} not, ${misfits.length} matched a wording but not the printed damage:`);
console.log(misfits.join('\n'));
