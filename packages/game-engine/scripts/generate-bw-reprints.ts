// Writes src/effects/bw-reprints.ts: every Black & White series card (Gen 5) that reprints an earlier one of the series, word
// for word (same name, attacks, Abilities and text), to the first print, whose effects it plays (index.ts). Run after
// changing the snapshot:
//   npx tsx scripts/generate-bw-reprints.ts
import { readFileSync, writeFileSync } from 'node:fs';

interface Row {
  id: string;
  name: string;
  category: string;
  effect?: string | null;
  attacks?: { name: string; cost: string[] | null; damage: string | number | null; effect: string | null }[] | null;
  abilities?: { name: string; effect: string | null }[] | null;
}

const SETS = ['bw1', 'bw2', 'bw3', 'bw4', 'bw5', 'bw6', 'dv1', 'bw7', 'bw8', 'bw9', 'bw10', 'bw11'];
const rows: Row[] = JSON.parse(readFileSync(new URL('../../db/prisma/data/tcgdex-wotc.json', import.meta.url), 'utf8')).cards;
const order = (id: string) => [SETS.indexOf(id.split('-')[0]!), Number.parseInt(id.split('-')[1]!.replace(/^RC/, ''), 10) || 0, id.includes('-RC') ? 1 : 0];
const text = (s: string | null | undefined) => (s ?? '').replace(/[’‘]/g, "'").replace(/\s+/g, ' ').trim();
/** What the card does: two cards with the same are one card to the effects. */
const signature = (r: Row) =>
  JSON.stringify([
    r.category,
    r.name,
    text(r.effect),
    (r.attacks ?? []).map((a) => [a.name, a.cost ?? [], String(a.damage ?? ''), text(a.effect)]),
    (r.abilities ?? []).map((a) => [a.name, text(a.effect)]),
  ]);

const first = new Map<string, string>();
const lines: string[] = [];
const cards = rows.filter((r) => SETS.includes(r.id.split('-')[0]!));
cards.sort((a, b) => {
  const [x, y] = [order(a.id), order(b.id)];
  return x[0]! - y[0]! || x[2]! - y[2]! || x[1]! - y[1]!;
});
for (const r of cards) {
  // Nothing to play: basic Energy and Pokémon with no text.
  if (r.category === 'Energy' && !text(r.effect)) continue;
  if (r.category === 'Pokemon' && !(r.attacks ?? []).some((a) => text(a.effect)) && !(r.abilities ?? []).length) continue;
  const sig = signature(r);
  const earlier = first.get(sig);
  if (earlier) lines.push(`  '${r.id}': '${earlier}', // ${r.name}`);
  else first.set(sig, r.id);
}

writeFileSync(
  new URL('../src/effects/bw-reprints.ts', import.meta.url),
  `// Generated by scripts/generate-bw-reprints.ts from the TCGdex snapshot: don't edit by hand.
// Black & White series cards that reprint an earlier one of the series word for word: each plays as the first print (index.ts).
export const BW_REPRINTS: Record<string, string> = {
${lines.join('\n')}
};
`,
);
console.log(`${lines.length} reprints`);
