// The generated effect data, worked out from the snapshot's cards: the text of src/effects/ex-template-data.ts and
// src/effects/bw-reprints.ts, as generate-ex-templates.ts and generate-bw-reprints.ts write them, and as the campaign's
// generated.test.ts checks the committed files against (so a changed template or snapshot can't leave them stale).
// Pure: it reads and writes no file.
import '../src/index.js';
import { matchTemplate, type TemplateUse } from '../src/effects/ex-templates.js';

/** A snapshot card, as far as the generators read it. */
export interface Row {
  id: string;
  name: string;
  category: string;
  effect?: string | null;
  attacks?: { name: string; cost: string[] | null; damage: string | number | null; effect: string | null }[] | null;
  abilities?: { name: string; effect: string | null }[] | null;
}

const TEMPLATE_SETS = [...Array.from({ length: 15 }, (_, i) => `ex${i + 2}`), 'dp1', 'dpp', 'dp2', 'dp3', 'dp4', 'dp5', 'dp6', 'dp7', 'pl1', 'pl2', 'pl3', 'pl4', 'hgss1', 'hgssp', 'hgss2', 'hgss3', 'hgss4', 'col1', 'bw1', 'bw2', 'bw3', 'bw4', 'bw5', 'bw6', 'dv1', 'bw7', 'bw8', 'bw9', 'bw10', 'bw11'];
/** A string in single quotes, as the code has them. */
const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/**
 * ex-template-data.ts: every attack of the EX sets after Ruby & Sapphire (ex2–ex16), Gen 4's and Gen 5's whose TCGdex
 * text matches one of the shared wordings (src/effects/ex-templates.ts). `misfits`: attacks that matched a wording but
 * not the printed damage, for the generator to print.
 */
export function exTemplateFile(rows: readonly Row[]): { text: string; matched: number; unmatched: number; misfits: string[] } {
  const order = (id: string) => [TEMPLATE_SETS.indexOf(id.split('-')[0]!), Number.parseInt(id.split('-')[1]!, 10) || 0];
  const lines: string[] = [];
  const misfits: string[] = [];
  let matched = 0;
  let unmatched = 0;
  for (const r of rows.filter((c) => c.category === 'Pokemon' && TEMPLATE_SETS.includes(c.id.split('-')[0]!)).sort((a, b) => order(a.id)[0]! - order(b.id)[0]! || order(a.id)[1]! - order(b.id)[1]!)) {
    const uses: [string, TemplateUse][] = [];
    // Each attack name once, as the API has them.
    for (const a of (r.attacks ?? []).filter((x, i, all) => all.findIndex((y) => y.name === x.name) === i)) {
      if (!a.effect) continue;
      const m = matchTemplate(a.effect, r.name, Number.parseInt(String(a.damage ?? ''), 10) || 0, a.cost ?? []);
      if (!m) unmatched++;
      else if ('misfit' in m) misfits.push(`${r.id} ${r.name} – ${a.name} (${a.damage ?? ''}): ${m.misfit}`);
      else {
        matched++;
        uses.push([a.name, m]);
      }
    }
    if (uses.length) lines.push(`  ${q(r.id)}: { ${uses.map(([name, use]) => `${/^[A-Za-z]+$/.test(name) ? name : q(name)}: [${use.map((a) => (typeof a === 'number' ? a : q(a))).join(', ')}]`).join(', ')} }, // ${r.name}`);
  }
  const text = [
    '// Generated by scripts/generate-ex-templates.ts from the TCGdex snapshot: the EX (ex2–ex16) and Gen 4 attacks whose wording is one of the',
    "// shared ones in ex-templates.ts, as [template, printed damage, ...the wording's numbers and words]. Don't edit by hand.",
    "import type { TemplateUse } from './ex-templates.js';",
    '',
    'export const EX_TEMPLATE_DATA: Record<string, Record<string, TemplateUse>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
  return { text, matched, unmatched, misfits };
}

const BW_SETS = ['bw1', 'bw2', 'bw3', 'bw4', 'bw5', 'bw6', 'dv1', 'bw7', 'bw8', 'bw9', 'bw10', 'bw11'];

/**
 * bw-reprints.ts: every Black & White series card (Gen 5) that reprints an earlier one of the series, word for word (same
 * name, attacks, Abilities and text), to the first print, whose effects it plays (index.ts).
 */
export function bwReprintsFile(rows: readonly Row[]): { text: string; count: number } {
  const order = (id: string) => [BW_SETS.indexOf(id.split('-')[0]!), Number.parseInt(id.split('-')[1]!.replace(/^RC/, ''), 10) || 0, id.includes('-RC') ? 1 : 0];
  const text = (s: string | null | undefined) => (s ?? '').replace(/[’‘]/g, "'").replace(/\s+/g, ' ').trim();
  /** What the card does: two cards with the same are one card to the effects. */
  const signature = (r: Row) =>
    JSON.stringify([
      r.category,
      r.name,
      text(r.effect),
      (r.attacks ?? []).map((a) => [a.name, a.cost ?? [], String(a.damage ?? ''), text(a.effect)]),
      (r.abilities ?? []).map((a) => [a.name, text(a.effect)]),
    ]);

  const first = new Map<string, string>();
  const lines: string[] = [];
  const cards = rows.filter((r) => BW_SETS.includes(r.id.split('-')[0]!));
  cards.sort((a, b) => {
    const [x, y] = [order(a.id), order(b.id)];
    return x[0]! - y[0]! || x[2]! - y[2]! || x[1]! - y[1]!;
  });
  for (const r of cards) {
    // Nothing to play: basic Energy and Pokémon with no text.
    if (r.category === 'Energy' && !text(r.effect)) continue;
    if (r.category === 'Pokemon' && !(r.attacks ?? []).some((a) => text(a.effect)) && !(r.abilities ?? []).length) continue;
    const sig = signature(r);
    const earlier = first.get(sig);
    if (earlier) lines.push(`  '${r.id}': '${earlier}', // ${r.name}`);
    else first.set(sig, r.id);
  }
  return {
    text: `// Generated by scripts/generate-bw-reprints.ts from the TCGdex snapshot: don't edit by hand.
// Black & White series cards that reprint an earlier one of the series word for word: each plays as the first print (index.ts).
export const BW_REPRINTS: Record<string, string> = {
${lines.join('\n')}
};
`,
    count: lines.length,
  };
}
