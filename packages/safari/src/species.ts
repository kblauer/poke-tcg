let units: Unit[] | undefined;

/** Every unit, in Pokédex order. */
export function allUnits(): Unit[] {
  if (units) return units;
  const byName = new Map(ROWS.map((r) => [r[1], r]));
  const stageOf = (row: Row): UnitStage => {
    const below = row[7] ? byName.get(row[7]) : undefined;
    if (row[7] && !below) throw new Error(`${row[1]} evolves from an unknown Pokémon, ${row[7]}`);
    return !below ? 'basic' : below[7] ? 'stage2' : 'stage1';
  };
  return (units = ROWS.map((row) => {
    const [dex, name, type, tier, attack, hp, keywords, from] = row;
    return { id: String(dex), dex, name, type, stage: stageOf(row), hp, attack, tier, abilities: keywords ? keywords.split(';').map(parseAbility) : [], evolvesFrom: from ?? null, ...(LEGENDARY.has(dex) && { legendary: true as const }) };
  }));
}
